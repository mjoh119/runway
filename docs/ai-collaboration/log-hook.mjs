#!/usr/bin/env node
// log-hook.mjs — Kiro session-log hook script
// Appends timestamped entries to docs/ai-collaboration/session-log.md
//
// Invoked by Kiro hooks:
//   node log-hook.mjs prompt   (UserPromptSubmit — logs the user's prompt)
//   node log-hook.mjs stop     (Stop — logs git status --short)
//
// Always exits 0 so it never blocks the agent.

import { appendFileSync, existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const LOG_PATH = join(__dirname, 'session-log.md');

const HEADER = `# AI Collaboration Session Log

This file is automatically generated by Kiro hooks.
Each entry records a prompt submission or agent completion during collaboration sessions.

---
`;

function ensureLog() {
  if (!existsSync(LOG_PATH)) {
    mkdirSync(__dirname, { recursive: true });
    writeFileSync(LOG_PATH, HEADER, 'utf8');
  }
}

function nowISO() {
  return new Date().toISOString();
}

function appendEntry(heading, body) {
  const entry = `\n## ${heading}\n**Timestamp:** ${nowISO()}\n\n${body}\n\n---\n`;
  appendFileSync(LOG_PATH, entry, 'utf8');
}

function readStdin() {
  return new Promise((resolve) => {
    let raw = '';
    let done = false;
    const finish = (v) => { if (!done) { done = true; resolve(v); } };
    process.stdin.setEncoding('utf8');
    process.stdin.on('data', (c) => { raw += c; });
    process.stdin.on('end', () => finish(raw));
    process.stdin.on('error', () => finish(''));
    // Fallback in case stdin never closes
    setTimeout(() => finish(raw), 1500);
  });
}

async function main() {
  const mode = process.argv[2];
  ensureLog();

  if (mode === 'prompt') {
    const raw = await readStdin();
    let event = {};
    try { event = JSON.parse(raw); } catch { /* invalid or empty stdin */ }
    // IDE exposes the prompt via USER_PROMPT env var; CLI via stdin JSON .prompt
    const prompt = process.env.USER_PROMPT ?? event.prompt ?? '(no prompt text captured)';
    appendEntry('Prompt', prompt);
  } else if (mode === 'stop') {
    let gitStatus = '';
    try {
      gitStatus = execSync('git status --short', { encoding: 'utf8' }).trim();
    } catch {
      gitStatus = '(git status unavailable)';
    }
    const body = gitStatus
      ? '```text\n' + gitStatus + '\n```'
      : '(no changes — working tree clean)';
    appendEntry('Agent finished', body);
  }

  process.exit(0);
}

main().catch(() => process.exit(0));
